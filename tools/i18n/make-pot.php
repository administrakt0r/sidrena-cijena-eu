<?php
/**
 * Translation catalogue builder.
 *
 * Extracts translatable strings from the plugin source and writes
 * `languages/sidrena-cijena.pot`. With `--locale=hr_HR` it also writes a
 * `.po` catalogue using the translations in `tools/i18n/hr_HR.php`.
 *
 * Usage (host PHP):
 *   php tools/i18n/make-pot.php
 *   php tools/i18n/make-pot.php --locale=hr_HR
 *
 * This is a development utility; it never runs at plugin runtime.
 *
 * @package SidrenaCijena\Tools
 */

$root = dirname( __DIR__, 2 );

$locale = '';
foreach ( $argv as $argument ) {
	if ( 0 === strpos( $argument, '--locale=' ) ) {
		$locale = substr( $argument, strlen( '--locale=' ) );
	}
}

$directories = array( $root . '/src', $root . '/templates', $root . '/sidrena-cijena.php' );

$strings = array();

foreach ( $directories as $path ) {
	if ( is_file( $path ) ) {
		$files = array( $path );
	} else {
		$files = sidrena_collect_php_files( $path );
	}

	foreach ( $files as $file ) {
		$contents = file_get_contents( $file );
		sidrena_extract_strings( $contents, $strings );
	}
}

ksort( $strings, SORT_NATURAL | SORT_FLAG_CASE );

$pot  = "# Copyright (C) 2026 Sidrena cijena contributors\n";
$pot .= "# This file is distributed under the GPL-2.0-or-later license.\n";
$pot .= "msgid \"\"\n";
$pot .= "msgstr \"\"\n";
$pot .= "\"Project-Id-Version: Sidrena cijena 0.1.0\\n\"\n";
$pot .= "\"Report-Msgid-Bugs-To: https://example.com/sidrena-cijena\\n\"\n";
$pot .= "\"POT-Creation-Date: " . gmdate( 'c' ) . "\\n\"\n";
$pot .= "\"MIME-Version: 1.0\\n\"\n";
$pot .= "\"Content-Type: text/plain; charset=UTF-8\\n\"\n";
$pot .= "\"Content-Transfer-Encoding: 8bit\\n\"\n";
$pot .= "\"X-Generator: tools/i18n/make-pot.php\\n\"\n";
$pot .= "\"X-Domain: sidrena-cijena\\n\"\n\n";

foreach ( $strings as $string => $unused ) {
	$pot .= 'msgid "' . sidrena_po_escape( $string ) . "\"\n";
	$pot .= "msgstr \"\"\n\n";
}

file_put_contents( $root . '/languages/sidrena-cijena.pot', $pot );

echo 'Wrote languages/sidrena-cijena.pot with ' . count( $strings ) . " strings.\n";

if ( '' !== $locale ) {
	$translations_file = $root . '/tools/i18n/' . $locale . '.php';

	if ( ! is_file( $translations_file ) ) {
		fwrite( STDERR, "No translation dictionary found at {$translations_file}\n" );
		exit( 1 );
	}

	$translations = require $translations_file;

	$po  = "# " . $locale . " translation for Sidrena cijena.\n";
	$po .= "# Generated by tools/i18n/make-pot.php --locale=" . $locale . "\n";
	$po .= "msgid \"\"\n";
	$po .= "msgstr \"\"\n";
	$po .= "\"Project-Id-Version: Sidrena cijena 0.1.0\\n\"\n";
	$po .= "\"Report-Msgid-Bugs-To: https://example.com/sidrena-cijena\\n\"\n";
	$po .= "\"POT-Creation-Date: " . gmdate( 'c' ) . "\\n\"\n";
	$po .= "\"PO-Revision-Date: " . gmdate( 'c' ) . "\\n\"\n";
	$po .= "\"MIME-Version: 1.0\\n\"\n";
	$po .= "\"Content-Type: text/plain; charset=UTF-8\\n\"\n";
	$po .= "\"Content-Transfer-Encoding: 8bit\\n\"\n";
	$po .= "\"Language: " . $locale . "\\n\"\n";
	$po .= "\"X-Generator: tools/i18n/make-pot.php\\n\"\n";
	$po .= "\"X-Domain: sidrena-cijena\\n\"\n\n";

	$translated = 0;
	$missing    = 0;

	foreach ( $strings as $string => $unused ) {
		$po .= 'msgid "' . sidrena_po_escape( $string ) . "\"\n";

		if ( isset( $translations[ $string ] ) && '' !== $translations[ $string ] ) {
			$po .= 'msgstr "' . sidrena_po_escape( $translations[ $string ] ) . "\"\n\n";
			++$translated;
		} else {
			$po .= "msgstr \"\"\n\n";
			++$missing;
		}
	}

	$po_file = $root . '/languages/' . $locale . '.po';
	file_put_contents( $po_file, $po );

	echo 'Wrote languages/' . $locale . ".po ({$translated} translated, {$missing} untranslated).\n";

	if ( 'hr_HR' === $locale ) {
		$mo = sidrena_compile_mo( $translations );
		file_put_contents( $root . '/languages/hr_HR.mo', $mo );
		echo "Wrote languages/hr_HR.mo (" . strlen( $mo ) . " bytes).\n";
	}
}

/**
 * Collect PHP files below a directory.
 *
 * @param string $directory Directory.
 * @return string[]
 */
function sidrena_collect_php_files( $directory ) {
	$files    = array();
	$iterator = new RecursiveIteratorIterator( new RecursiveDirectoryIterator( $directory ) );

	foreach ( $iterator as $file ) {
		if ( $file->isFile() && 'php' === $file->getExtension() ) {
			$files[] = $file->getPathname();
		}
	}

	sort( $files );

	return $files;
}

/**
 * Extract gettext-style calls from source code.
 *
 * @param string   $contents Source.
 * @param string[] $strings  Collected strings (by reference).
 * @return void
 */
function sidrena_extract_strings( $contents, &$strings ) {
	$pattern = '/(?:__|_e|esc_html__|esc_attr__|esc_html_e|esc_attr_e)\s*\(\s*([\'"])((?:\\\\.|(?!\1).)*)\1\s*,\s*[\'"]sidrena-cijena[\'"]/s';

	if ( preg_match_all( $pattern, $contents, $matches, PREG_SET_ORDER ) ) {
		foreach ( $matches as $match ) {
			$quote  = $match[1];
			$string = $match[2];

			if ( "'" === $quote ) {
				$string = str_replace( array( '\\\\', "\\'" ), array( '\\', "'" ), $string );
			} else {
				$string = stripcslashes( $string );
			}

			$strings[ $string ] = true;
		}
	}
}

/**
 * Escape a string for a PO file.
 *
 * @param string $value Value.
 * @return string
 */
function sidrena_po_escape( $value ) {
	return str_replace(
		array( '\\', '"', "\n", "\t" ),
		array( '\\\\', '\\"', '\\n', '\\t' ),
		$value
	);
}

/**
 * Compile a gettext dictionary to a binary MO file.
 *
 * Implements the GNU MO format directly so the build does not depend on
 * msgfmt being installed.
 *
 * @param array $translations msgid => msgstr map.
 * @return string Binary MO contents.
 */
function sidrena_compile_mo( $translations ) {
	$entries = array();

	foreach ( $translations as $original => $translation ) {
		if ( '' === $translation ) {
			continue;
		}

		$entries[ $original ] = $translation;
	}

	ksort( $entries );

	$count       = count( $entries );
	$original    = '';
	$translated  = '';
	$original_table    = '';
	$translation_table = '';

	$offset = 28 + ( $count * 16 );

	$index = 0;
	foreach ( $entries as $msgid => $msgstr ) {
		$original_length    = strlen( $msgid );
		$translated_length  = strlen( $msgstr );

		$original_table    .= pack( 'VV', $original_length, $offset + $index );
		$translation_table .= pack( 'VV', $translated_length, $offset + $index + $original_length + 1 );

		$original   .= $msgid . "\0";
		$translated .= $msgstr . "\0";

		$index += $original_length + $translated_length + 2;
	}

	$header  = pack( 'V', 0x950412de ); // Magic.
	$header .= pack( 'V', 0 );          // Revision.
	$header .= pack( 'V', $count );     // Number of strings.
	$header .= pack( 'V', 28 );         // Offset of original table.
	$header .= pack( 'V', 28 + ( $count * 8 ) ); // Offset of translation table.
	$header .= pack( 'V', 0 );          // Hash table size.
	$header .= pack( 'V', 28 + ( $count * 16 ) ); // Hash table offset.

	return $header . $original_table . $translation_table . $original . $translated;
}
